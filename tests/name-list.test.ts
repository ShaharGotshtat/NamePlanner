import { describe, expect, it } from "vitest";
import { parseNameList } from "@/lib/name-list";

describe("parseNameList", () => {
  it.each([
    ["דני, מיכל", ["דני", "מיכל"]],
    ["דני ומיכל", ["דני", "מיכל"]],
    ["דני, מיכל ויואב", ["דני", "מיכל", "יואב"]],
    ["דני מיכל יואב", ["דני", "מיכל", "יואב"]],
    ["דני\nמיכל\n\nיואב", ["דני", "מיכל", "יואב"]],
    ["1. דני\n2. מיכל", ["דני", "מיכל"]],
    ["- דני\n- מיכל", ["דני", "מיכל"]],
    ["דני / מיכל; יואב", ["דני", "מיכל", "יואב"]],
    ["דני ו מיכל", ["דני", "מיכל"]],
    ["בת אל, יואב", ["בת אל", "יואב"]],
    ["דני, ורד", ["דני", "ורד"]],
    ["ורד ודני", ["ורד", "דני"]],
    ["Dan, Michal and Yoav", ["Dan", "Michal", "Yoav"]],
    ["דני, דני, מיכל", ["דני", "מיכל"]],
    ["", []],
    ["  ,  ", []],
  ])("%j", (input, expected) => {
    expect(parseNameList(input)).toEqual(expected);
  });
});
