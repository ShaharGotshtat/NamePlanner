import { readFileSync, writeFileSync } from "node:fs";
import type { NameEntry } from "../src/lib/types";
import { computeFeatures } from "../src/lib/names/features";

const names: NameEntry[] = JSON.parse(readFileSync("data/names.sample.json", "utf8"));

const text = (value: string | null) => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);
const json = (value: unknown) => `${text(JSON.stringify(value))}::jsonb`;
const array = (values: string[]) => `array[${values.map(text).join(", ")}]::text[]`;

const rows = names.map((n) =>
  [
    n.id,
    text(n.nameHe),
    text(n.niqqud),
    array(n.translit),
    n.sexRatio,
    text(n.meaningHe),
    text(n.origin),
    text(n.biblicalRef),
    json(n.tags),
    json(computeFeatures(n.nameHe, n.translit[0])),
    json(n.stats),
  ].join(", "),
);

const sql = `-- Generated by \`npm run db:seed-sql\` from data/names.sample.json. Do not edit by hand.
insert into names (id, name_he, niqqud, translit, sex_ratio, meaning_he, origin, biblical_ref, tags, features, stats) values
${rows.map((r) => `  (${r})`).join(",\n")}
on conflict (id) do nothing;

insert into app_settings (key, value) values ('daily_budget_usd', '3') on conflict (key) do nothing;
`;

writeFileSync("db/seed.sql", sql);
console.log(`Wrote ${names.length} names to db/seed.sql`);
